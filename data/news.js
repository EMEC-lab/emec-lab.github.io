/* =========================================================================
 * data/news.js  —  연구실 소식
 *
 * ┌───────────────────────────────────────────────────────────────────┐
 * │ 새 소식 추가하는 법                                                  │
 * │  1. 아래 NEWS 배열의 맨 위에 아래 덩어리를 복사해 붙여넣는다.          │
 * │  2. 내용을 바꾼다.                                                  │
 * │  3. 저장하고 index.html 을 새로고침하면 바로 보인다.                  │
 * │                                                                   │
 * │   {                                                               │
 * │     date: "2026-09-01",                                           │
 * │     category: "paper",                                            │
 * │     text: "여기에 한두 문장으로 씁니다.",                             │
 * │     link: "",                                                     │
 * │     image: ""                                                     │
 * │   },                                                              │
 * │                                                                   │
 * │ ⚠ 쉼표(,)를 빠뜨리거나 큰따옴표를 닫지 않으면 페이지가 비어 보인다.     │
 * │   그럴 때는 브라우저에서 F12 → Console 을 보면 몇 번째 줄인지 나온다.   │
 * └───────────────────────────────────────────────────────────────────┘
 *
 * 항목 설명
 *   date      "YYYY-MM-DD"  반드시 이 형식. 순서는 자동으로 최신순 정렬된다
 *   category  paper | award | member | project | etc
 *               paper   논문 게재·승인
 *               award   수상
 *               member  구성원 합류·졸업
 *               project 과제 선정·착수
 *               etc     그 외
 *             화면 라벨은 data/site.js 의 newsCategories 에서 가져온다
 *   text      1~3문장. 국내 소식은 국문, 국제 논문 게재는 영문 등 상황에 맞게
 *   link      선택. 주소를 넣으면 문장 전체가 링크가 된다. 없으면 "" 로 둔다
 *   image     선택. "images/news/파일명.jpg" 형태. 없으면 "" 로 둔다
 *             → 사진은 images/resize.ps1 로 줄인 뒤 넣을 것 (README 참고)
 * ========================================================================= */

